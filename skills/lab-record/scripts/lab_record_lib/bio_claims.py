"""Emit a bio-constants `bio_claims.toml` from the catalog (cross-check input only).

Values flow catalog -> claims file; live database values are never written back (design 261026).
UniProt claims are made only for a stated `mass_da` / `length_aa`; a reaction `keq` becomes an
eQuilibrator claim, and when a condition is missing it is emitted commented out with a BLIND note.
"""
from __future__ import annotations

import json

from .catalog import KEQ_CONDITIONS, Catalog

HEADER = ("# Generated by `lab_record.py bio-claims` from catalog.json. Cross-check only:\n"
          "# never copy a live value back into the catalog.\n"
          "# Run: \"$PY\" -I ~/.claude/skills/bio-constants/scripts/biodb/bio_const.py check <this file>\n")


def _s(value) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _num(value) -> str:
    return repr(float(value)) if isinstance(value, float) else str(value)


def _block(lines: list[str], commented: bool) -> list[str]:
    return [("# " + ln if commented and ln else ln) for ln in lines]


def _uniprot_claims(cat: Catalog) -> list[str]:
    out: list[str] = []
    for e in cat.entries:
        acc = e.data.get("uniprot")
        if e.kind != "enzyme" or not acc:
            continue
        for key, fld, unit in (("mass_da", "mass", "Da"), ("length_aa", "length", "aa")):
            if key in e.data:
                out += ["[[claim]]", f"name = {_s(f'{e.name} {fld} (UniProt {acc})')}", 'source = "uniprot"',
                        f"id = {_s(acc)}", f'field = "{fld}"', f"claimed = {_s(e.data[key])}",
                        f'unit = "{unit}"', ""]
    return out


def _keq_claims(cat: Catalog) -> list[str]:
    out: list[str] = []
    for e in cat.entries:
        keq = e.data.get("keq")
        if e.kind != "reaction" or not keq:
            continue
        missing = [k for k in KEQ_CONDITIONS if k not in keq]
        if not e.data.get("equation"):
            missing.insert(0, "equation")
        lines = ["[[claim]]", f"name = {_s(f'{e.name} Keq')}", f"reaction = {_s(e.data.get('equation', ''))}"]
        lines += [f"{'temperature' if k == 'temperature_K' else k} = {_num(keq[k])}"
                  for k in KEQ_CONDITIONS if k in keq]
        lines.append(f"claimed_keq = {_num(keq['value'])}")
        if keq.get("source"):
            lines.append(f"# catalog source: {keq['source']}")
        if missing:
            out.append(f"# BLIND: {e.label} keq is missing {', '.join(missing)}; not checkable until stated")
        out += _block(lines, commented=bool(missing)) + [""]
    return out


def build(cat: Catalog) -> str:
    body = _uniprot_claims(cat) + _keq_claims(cat)
    if not body:
        body = ["# no claims: the catalog states no uniprot mass/length and no reaction keq", ""]
    return HEADER + "\n" + "\n".join(body).rstrip("\n") + "\n"
